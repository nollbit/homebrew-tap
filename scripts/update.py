#!/usr/bin/env python3
"""Regenerates Formula/monolepo.rb from the tools manifest Monolepo publishes."""
import json
import pathlib
import re
import sys
import urllib.request

SERVER = "https://monolepo.com"
PLATFORMS = {("macos", "arm"): "darwin-arm64", ("linux", "intel"): "linux-amd64", ("linux", "arm"): "linux-arm64"}
DIGEST = re.compile(r"^[0-9a-f]{64}$")


def tool(manifest, name):
    entry = manifest["tools"][name]
    path, digest = entry["path"], entry["sha256"]
    if not DIGEST.match(digest) or path != f"/tools/v/{digest}/{name}":
        raise ValueError(f"unexpected manifest entry for {name}")
    return SERVER + path, digest


def platform_block(manifest, suffix):
    cli_url, cli_sum = tool(manifest, f"monolepo-{suffix}")
    helper_url, helper_sum = tool(manifest, f"docker-credential-monolepo-{suffix}")
    return f'''      url "{cli_url}"
      sha256 "{cli_sum}"

      resource "docker-credential-monolepo" do
        url "{helper_url}"
        sha256 "{helper_sum}"
      end'''


def render(manifest):
    version = manifest["version"]
    if not re.fullmatch(r"[0-9]+", version):
        raise ValueError("unexpected version")
    mac = platform_block(manifest, PLATFORMS[("macos", "arm")])
    linux_intel = platform_block(manifest, PLATFORMS[("linux", "intel")])
    linux_arm = platform_block(manifest, PLATFORMS[("linux", "arm")])
    return f'''# Generated by scripts/update.py from {SERVER}/tools/manifest.json; do not edit.
class Monolepo < Formula
  desc "Command-line client for Monolepo, with the Lore client included"
  homepage "{SERVER}"
  version "{version}"

  on_macos do
    depends_on arch: :arm64

    on_arm do
{mac}
    end
  end

  on_linux do
    on_intel do
{linux_intel}
    end

    on_arm do
{linux_arm}
    end
  end

  def install
    bin.install Dir["monolepo-*"].first => "monolepo"
    resource("docker-credential-monolepo").stage do
      bin.install Dir["docker-credential-monolepo-*"].first => "docker-credential-monolepo"
    end
    bin.install_symlink "monolepo" => "lore"
  end

  test do
    assert_match "lore", shell_output("#{{bin}}/lore --version")
  end
end
'''


def main():
    with urllib.request.urlopen(f"{SERVER}/tools/manifest.json", timeout=30) as response:
        manifest = json.load(response)
    formula = pathlib.Path(__file__).resolve().parent.parent / "Formula" / "monolepo.rb"
    text = render(manifest)
    if formula.exists() and formula.read_text() == text:
        print(f"monolepo {manifest['version']} is current")
        return
    formula.write_text(text)
    print(f"monolepo updated to {manifest['version']}")


if __name__ == "__main__":
    sys.exit(main())
